def _select_pattern(
    patterns: list,
    recent_patterns: list,
    platform_hint: str = "threads",
    hour: int = 12,
    excluded_categories: set = None,
) -> dict:
    """
    投稿パターンを重み付きランダムで選択する。

    category + daily_limit の仕組み:
        同じ category を持つパターンは、バッチ内で daily_limit 回まで。
        run() が excluded_categories を管理し、上限に達したカテゴリを渡す。

    format の種類（参考）:
        short  … 1〜4行、120字以内のひとこと投稿（ici_gon / emoji_comment 等）
        medium … 120〜280字の通常投稿（ほとんどのパターン）
        long   … 280字超 or 箇条書き一覧型（hoshi_betsu / ranking / menu_guide 等）
        tree   … 複数投稿ツリー（empathy_thread）
    """
    import random
    excluded_cats = excluded_categories or set()
    blocked = set(recent_patterns)

    # プラットフォーム対応 & カテゴリ制限を除外
    available = [
        p for p in patterns
        if p.get("id") not in blocked
        and platform_hint in p.get("platforms", ["threads"])
        and p.get("category", "") not in excluded_cats
    ]
    if not available:
        # recent_patterns ブロックを解除して再試行（全件消費ガード）
        available = [
            p for p in patterns
            if platform_hint in p.get("platforms", ["threads"])
            and p.get("category", "") not in excluded_cats
        ]
    if not available:
        # カテゴリ制限も解除（フォールバック）
        available = [p for p in patterns if platform_hint in p.get("platforms", ["threads"])]

    # 時間帯・曜日による weight ブースト
    from datetime import datetime, timezone
    _today_wd = datetime.now(timezone.utc).weekday()  # 月=0
    weights = []
    for p in available:
        w = p.get("weight", 1.0)
        pid = p.get("id", "")

        # preferred_hours ブースト: 最優先時間帯は 2.5x
        if hour in p.get("preferred_hours", []):
            w *= 2.5

        # 月曜の weekly_forecast は追加 1.5x（月曜 preferred_hours との合計 = 3.75x）
        if _today_wd == 0 and pid == "weekly_forecast":
            w *= 1.5

        weights.append(w)

    return random.choices(available, weights=weights, k=1)[0]


def _select_theme(theme_tree: dict, recent_themes: list, schedule_hint: str = "") -> str:
    import random

    def flatten(node, prefix=""):
        items = []
        for k, v in node.items():
            label = f"{prefix}/{k}" if prefix else k
            if isinstance(v, dict):
                items.extend(flatten(v, label))
            else:
                items.append(label)
        return items

    all_themes = flatten(theme_tree)

    # スケジュールヒントに近いテーマを優先
    if schedule_hint:
        hint_themes = [t for t in all_themes if any(
            keyword in t for keyword in schedule_hint.replace("・", "/").split("/")
        )]
        if hint_themes:
            return random.choice(hint_themes)

    recent_set = set(recent_themes)
    fresh = [t for t in all_themes if t not in recent_set]
    return random.choice(fresh if fresh else all_themes)


